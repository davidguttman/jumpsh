import { parseArgs } from 'node:util';
import { execSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { getBestLocalCertStatus } from '../cert-status.js';
import { detectDomain, detectDomainFromCerts, formatDashUrl } from '../domain.js';
import { ensureManagementToken, managementAccessLines } from '../management-auth.js';
import { launchBrowser } from '../browser.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(__dirname, '..', '..');
const JUMPSH_DIR = path.join(os.homedir(), '.jump.sh');

export default async function install(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      help: { type: 'boolean', short: 'h', default: false },
    },
  });

  if (values.help) {
    console.log(`Usage: jump.sh install

Install the jump.sh daemon service. If JUMPSH_HTTPS=true and certs
are missing, automatically downloads them from the jump.sh server.

Options:
  --help, -h    Show this help
`);
    process.exit(0);

  }

  const platform = os.platform();
  if (platform !== 'darwin' && platform !== 'linux') {
    console.error(`Unsupported platform: ${platform}. Only macOS and Linux are supported.`);
    process.exit(1);
  }

  ensureManagementToken();

  // Track created artifacts for rollback on failure
  const created = [];

  let port;
  try {
    ({ port } = await doInstall(platform, created));
  } catch (err) {
    console.error(`\nInstall failed: ${err.message}`);
    // Rollback created artifacts
    if (created.length > 0) {
      console.log('Rolling back created artifacts...');
      for (const artifact of created.reverse()) {
        try {
          if (fs.existsSync(artifact)) {
            fs.unlinkSync(artifact);
            console.log(`  Removed: ${artifact}`);
          }
        } catch { /* best effort */ }
      }
    }
    process.exit(1);
  }

  const domain = detectDomain();
  const hasDomain = detectDomainFromCerts() || process.env.JUMPSH_DOMAIN;
  const dashUrl = formatDashUrl(hasDomain ? domain : 'jump.sh', port);

  console.log('');
  console.log('\u2713 jump.sh daemon installed and running');
  console.log('');

  if (hasDomain) {
    console.log(`  Your domain:    ${domain}`);
  }
  console.log(`  Dashboard:      ${dashUrl}`);
  for (const line of managementAccessLines()) console.log(`  ${line}`);
  if (!hasDomain) {
    console.log('  For remote access: jump.sh register');
  }

  // Auto-open dashboard (best effort, argv launch without a shell)
  await launchBrowser(dashUrl, { platform });
}

async function doInstall(platform, created) {
  // Step 1: Create state directory
  fs.mkdirSync(JUMPSH_DIR, { recursive: true });
  fs.mkdirSync(path.join(JUMPSH_DIR, 'logs'), { recursive: true });
  console.log(`State directory: ${JUMPSH_DIR}`);

  // Step 2: Ensure certs if HTTPS is enabled
  const httpsEnabled = process.env.JUMPSH_HTTPS === 'true';
  if (httpsEnabled) {
    const { ensureHttpsCerts } = await import('./certs.js');
    const domain = detectDomain();
    const { results } = await ensureHttpsCerts({ domain });
    if (results.some((r) => r.error)) {
      console.log('\nCert refresh failed. You can fetch them later:');
      console.log('  jump.sh certs');
    }
    const certStatus = getBestLocalCertStatus({ domain });

    if (certStatus.status === 'valid') {
      console.log(`TLS certificates: valid until ${certStatus.expires_at}`);
    } else {
      console.log(`TLS certificates: not healthy (${certStatus.status}).`);
    }
  }

  // Step 3: Resolve the daemon exec command for the wrapper script
  const wrapperConfig = resolveDaemonWrapperConfig();

  // Step 4: Write wrapper script
  const wrapperPath = path.join(JUMPSH_DIR, 'jumpsh-daemon.sh');
  const wrapperContent = generateDaemonWrapper(wrapperConfig);
  fs.writeFileSync(wrapperPath, wrapperContent, { mode: 0o755 });
  created.push(wrapperPath);
  console.log(`Wrapper script: ${wrapperPath}`);

  // Step 5: Write and enable service file
  if (platform === 'darwin') {
    await installMacOS(wrapperPath, created);
    return { port: 443 };  // hint only; actual port determined at runtime
  } else {
    return await installLinux(wrapperPath, created);
  }
}

export function generateDaemonWrapper({ cwd, execCommand }) {
  return `#!/usr/bin/env bash
# jump.sh daemon wrapper — resolves node via version managers
# Regenerated by 'jump.sh install'

# Try mise
if command -v mise >/dev/null 2>&1; then
  for rc in "$HOME/.local/share/mise/activate.sh" \\
            "$HOME/.config/mise/activate.sh"; do
    if [ -f "$rc" ]; then
      eval "$(mise activate bash 2>/dev/null)" 2>/dev/null
      break
    fi
  done
fi

# Try fnm
if [ -d "$HOME/.fnm" ]; then
  eval "$("$HOME/.fnm/fnm" env 2>/dev/null)" 2>/dev/null
fi

# Try nvm
NVM_DIR="\${NVM_DIR:-$HOME/.nvm}"
if [ -s "$NVM_DIR/nvm.sh" ]; then
  . "$NVM_DIR/nvm.sh" 2>/dev/null
fi

cd ${shellQuote(cwd)} 2>/dev/null
exec ${execCommand}
`;
}
async function installMacOS(wrapperPath, created) {
  const plistDir = path.join(os.homedir(), 'Library', 'LaunchAgents');
  fs.mkdirSync(plistDir, { recursive: true });
  const plistPath = path.join(plistDir, 'sh.jump.daemon.plist');

  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>sh.jump.daemon</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>${wrapperPath}</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>${JUMPSH_DIR}/logs/daemon.log</string>
  <key>StandardErrorPath</key><string>${JUMPSH_DIR}/logs/daemon.err</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>JUMPSH_HTTPS</key><string>true</string>
    <key>HOME</key><string>${os.homedir()}</string>
  </dict>
</dict>
</plist>
`;

  fs.writeFileSync(plistPath, plist);
  created.push(plistPath);
  console.log(`LaunchAgent: ${plistPath}`);

  try {
    execSync(`launchctl bootstrap gui/$(id -u) "${plistPath}" 2>/dev/null || launchctl load -w "${plistPath}"`, {
      stdio: 'inherit',
    });
    console.log('Daemon started via launchd.');
  } catch {
    console.log('Note: Could not start daemon. You may need to load it manually or run `jump.sh` in foreground.');
  }
}

async function installLinux(wrapperPath, created) {
  const unitDir = path.join(os.homedir(), '.config', 'systemd', 'user');
  fs.mkdirSync(unitDir, { recursive: true });
  const unitPath = path.join(unitDir, 'jumpsh.service');

  // Server auto-tries port 443 and falls back to 4443 if binding fails,
  // so we no longer need to set JUMPSH_PORT explicitly.
  const canBind443 = checkNodeCanBind();
  const envLines = 'Environment=JUMPSH_HTTPS=true';
  if (!canBind443) {
    const nodePath = process.execPath;
    console.log(`\nNote: Port 443 requires cap_net_bind_service on node.`);
    console.log(`  To enable: sudo setcap cap_net_bind_service=+ep "${nodePath}"`);
    console.log('  Server will automatically fall back to port 4443.\n');
  }

  const unit = `[Unit]
Description=jump.sh local dev daemon
After=network.target

[Service]
Type=simple
ExecStart=/bin/bash ${wrapperPath}
Restart=always
RestartSec=3
${envLines}

[Install]
WantedBy=default.target
`;

  fs.writeFileSync(unitPath, unit);
  created.push(unitPath);
  console.log(`Systemd unit: ${unitPath}`);

  try {
    execSync('systemctl --user daemon-reload', { stdio: 'inherit' });
    execSync('systemctl --user enable --now jumpsh', { stdio: 'inherit' });
    console.log('Daemon started via systemd.');
  } catch {
    console.log('Note: Could not enable daemon via systemd. Run `jump.sh` in foreground instead.');
  }

  return { port: canBind443 ? 443 : 4443 };  // hint only; actual port determined at runtime
}

function checkNodeCanBind() {
  try {
    const nodePath = process.execPath;
    const output = execSync(`getcap "${nodePath}" 2>/dev/null`, { encoding: 'utf8' });
    return output.includes('cap_net_bind_service');
  } catch {
    return false;
  }
}

export function resolveDaemonWrapperConfig(options = {}) {
  const packageRoot = options.packageRoot || PACKAGE_ROOT;
  const env = options.env || process.env;
  const homeDir = options.homeDir || os.homedir();

  if (isNpxRun(packageRoot, env)) {
    const npxPath = Object.prototype.hasOwnProperty.call(options, 'npxPath')
      ? options.npxPath
      : resolveNpxPath();

    return {
      cwd: homeDir,
      execCommand: `${shellQuote(npxPath || 'npx')} --yes jump.sh@latest server`,
    };
  }

  return {
    cwd: packageRoot,
    execCommand: `${resolveGlobalBin({ packageRoot, binExists: options.binExists })} server`,
  };
}

export function isNpxRun(packageRoot = PACKAGE_ROOT, env = process.env) {
  // npx installs packages into transient _npx cache roots. If the daemon
  // wrapper cd's back there and runs npx again, npm can recursively resolve
  // from stale/transient package paths under systemd/launchd.
  const execPath = env.npm_execpath || '';
  if (execPath.includes('npx')) return true;
  if (packageRoot.includes('_npx') || packageRoot.includes('.npm/_npx')) return true;
  return false;
}

export function resolveNpxPath(commandRunner = execSync) {
  try {
    const output = commandRunner('command -v npx', {
      encoding: 'utf8',
      shell: '/bin/sh',
    });
    return output.trim() || null;
  } catch {
    return null;
  }
}

export function resolveGlobalBin({ packageRoot = PACKAGE_ROOT, binExists = fs.existsSync } = {}) {
  // Use the actual path to bin/jumpsh.js from our known package root.
  // Since we already blocked npx above, packageRoot is a stable location
  // (global install or a local project checkout).
  const binPath = path.join(packageRoot, 'bin', 'jumpsh.js');
  if (!binExists(binPath)) {
    throw new Error(`Cannot find jumpsh binary at ${binPath}`);
  }
  return `node ${shellQuote(binPath)}`;
}

export function shellQuote(value) {
  return `'${String(value).replaceAll("'", `'"'"'`)}'`;
}
